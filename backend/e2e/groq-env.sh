# Source this to point EVERY LLM-dependent service at Groq (openai/gpt-oss-120b) for an isolated test run.
# Gemini stays the default everywhere else; nothing here is read unless this file is sourced.
# GROQ_API_KEY comes from backend/.env (gitignored) — it is never written here.
M="${GROQ_MODEL:-openai/gpt-oss-120b}"
for v in RAG QUERY_ROUTER GREETING QUERY_REWRITE LECTURE_SUMMARY GUARDRAIL QUERY_DECOMPOSITION ADAPTIVE_RETRIEVAL ANSWER_VERIFICATION OUTPUT_FORMAT_REPAIR; do
  export "${v}_LLM_PROVIDER=groq"
done
export RAG_ANSWER_MODEL="$M" RAG_ANSWER_FALLBACK_MODEL="$M" QUERY_ROUTER_LLM_MODEL="$M" GREETING_LLM_MODEL="$M" QUERY_REWRITE_LLM_MODEL="$M" \
       LECTURE_SUMMARY_LLM_MODEL="$M" GUARDRAIL_LLM_MODEL="$M" QUERY_DECOMPOSITION_LLM_MODEL="$M" ADAPTIVE_RETRIEVAL_LLM_MODEL="$M" \
       ANSWER_VERIFICATION_LLM_MODEL="$M" OUTPUT_FORMAT_REPAIR_LLM_MODEL="$M"
# gpt-oss reasons before answering and the free tier queues: the short Gemini-era timeouts would trip.
export GREETING_LLM_TIMEOUT_MS=30000 GUARDRAIL_LLM_TIMEOUT_MS=30000 QUERY_DECOMPOSITION_LLM_TIMEOUT_MS=30000 \
       ADAPTIVE_RETRIEVAL_LLM_TIMEOUT_MS=30000 ANSWER_VERIFICATION_LLM_TIMEOUT_MS=45000 OUTPUT_FORMAT_REPAIR_LLM_TIMEOUT_MS=30000
export HEALTH_GEMINI_CHECK_ENABLED=false
export GROQ_RUN_TOKEN_BUDGET="${GROQ_RUN_TOKEN_BUDGET:-90000}"
